// Helper to calculate total database stats
export const getDatabaseStats = () => {
  const totalCars = GARAGE_CARS.length;
  const approvedCars = GARAGE_CARS.filter(c => c.isCalvinApproved).length;
  const totalValuation = GARAGE_CARS.reduce((sum, c) => sum + c.cost, 0);
  const brandsCount = new Set(GARAGE_CARS.map(c => c.brand)).size;

  return {
    totalCars,
    approvedCars,
    totalValuation,
    totalValuationFormatted: `₹${(totalValuation / 10000000).toFixed(0)} Crore+`,
    brandsCount
  };
};
